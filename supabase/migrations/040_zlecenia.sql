-- 040: Zlecenia – dodatkowe zadania od administratora (Michał) dla pracowników.
-- Zleca tylko administrator; pracownik widzi wyłącznie swoje zlecenia. Przebieg:
-- nowe → w toku → (pytanie) → zgłoszone do sprawdzenia → zaakceptowane albo „popraw” (wraca do w toku).
-- Każde zdarzenie: powiadomienie push + e-mail (funkcje „push” i „mail”, wywoływane z bazy przez edge_call).

create table if not exists public.zlecenia (
  id           uuid primary key default gen_random_uuid(),
  no           int generated by default as identity,
  title        text not null check (length(title) between 1 and 200),
  body         text check (body is null or length(body) <= 5000),
  assignee_id  uuid not null references public.team_members(id) on delete cascade,
  created_by   uuid references public.team_members(id) on delete set null default public.current_member_id(),
  client_id    uuid references public.clients(id) on delete set null,
  due_date     date,
  priority     text not null default 'normalny' check (priority in ('normalny', 'pilne')),
  steps        jsonb not null default '[]'::jsonb,
  status       text not null default 'nowe' check (status in ('nowe', 'w_toku', 'pytanie', 'zgloszone', 'zaakceptowane', 'anulowane')),
  reported_at  timestamptz,
  accepted_at  timestamptz,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists zlecenia_assignee_idx on public.zlecenia (assignee_id, status);

create table if not exists public.zlecenia_wpisy (
  id           uuid primary key default gen_random_uuid(),
  zlecenie_id  uuid not null references public.zlecenia(id) on delete cascade,
  author_id    uuid references public.team_members(id) on delete set null default public.current_member_id(),
  kind         text not null default 'komentarz' check (kind in ('komentarz', 'pytanie', 'zgloszenie', 'poprawka', 'akceptacja', 'status')),
  body         text check (body is null or length(body) <= 3000),
  created_at   timestamptz not null default now()
);
create index if not exists zlecenia_wpisy_idx on public.zlecenia_wpisy (zlecenie_id, created_at);

create trigger zlecenia_touch before update on public.zlecenia for each row execute function public.touch_row();

alter table public.zlecenia enable row level security;
create policy zl_select on public.zlecenia for select to authenticated
  using ((select public.is_admin()) or assignee_id = (select public.current_member_id()));
create policy zl_insert on public.zlecenia for insert to authenticated with check ((select public.is_admin()));
create policy zl_update on public.zlecenia for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy zl_delete on public.zlecenia for delete to authenticated using ((select public.is_admin()));
grant select, insert, update, delete on public.zlecenia to authenticated;

alter table public.zlecenia_wpisy enable row level security;
create policy zw_select on public.zlecenia_wpisy for select to authenticated
  using (exists (select 1 from public.zlecenia z where z.id = zlecenie_id
    and ((select public.is_admin()) or z.assignee_id = (select public.current_member_id()))));
create policy zw_insert on public.zlecenia_wpisy for insert to authenticated
  with check (kind = 'komentarz' and author_id = (select public.current_member_id()) and exists (select 1 from public.zlecenia z where z.id = zlecenie_id
    and ((select public.is_admin()) or z.assignee_id = (select public.current_member_id()))));
grant select, insert on public.zlecenia_wpisy to authenticated;

-- powiadomienia (push + e-mail) – nigdy nie blokują zapisu
create or replace function public.zlecenie_notify(p_id uuid, p_ev text)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.push_call(jsonb_build_object('event', 'zlecenie', 'id', p_id, 'ev', p_ev, 'actor', public.current_member_id()));
  if p_ev in ('nowe', 'pytanie', 'zgloszone', 'poprawka', 'odpowiedz', 'zaakceptowane') then
    perform public.edge_call('mail', jsonb_build_object('action', 'zlecenie', 'id', p_id, 'ev', p_ev));
  end if;
exception when others then null;
end $$;
revoke all on function public.zlecenie_notify(uuid, text) from public, anon, authenticated;

create or replace function public.zlecenie_on_insert() returns trigger
language plpgsql security definer set search_path = public as $$
begin perform public.zlecenie_notify(new.id, 'nowe'); return null; end $$;
create trigger zlecenia_new after insert on public.zlecenia for each row execute function public.zlecenie_on_insert();

-- komentarz → push do drugiej strony (bez e-maila)
create or replace function public.zlecenie_on_comment() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.kind = 'komentarz' then perform public.push_call(jsonb_build_object('event', 'zlecenie', 'id', new.zlecenie_id, 'ev', 'komentarz', 'actor', new.author_id, 'wpis', new.id)); end if;
  return null;
exception when others then return null;
end $$;
create trigger zlecenia_comment after insert on public.zlecenia_wpisy for each row execute function public.zlecenie_on_comment();

-- akcje w zleceniu: pracownik (start, pytanie, zglos), administrator (akceptuj, popraw, odpowiedz, anuluj, wznow)
create or replace function public.zlecenie_akcja(p_id uuid, p_akcja text, p_tekst text default null)
returns text language plpgsql security definer set search_path = public as $$
declare z public.zlecenia%rowtype; me uuid := public.current_member_id(); adm boolean := public.is_admin(); txt text := nullif(trim(coalesce(p_tekst, '')), '');
begin
  select * into z from public.zlecenia where id = p_id for update;
  if not found or me is null or (not adm and z.assignee_id <> me) then raise exception 'Brak dostępu do zlecenia'; end if;
  if length(coalesce(txt, '')) > 3000 then raise exception 'Za długi tekst'; end if;

  if p_akcja = 'start' and z.assignee_id = me and z.status in ('nowe', 'pytanie') then
    update public.zlecenia set status = 'w_toku' where id = p_id;
  elsif p_akcja = 'pytanie' and z.assignee_id = me and z.status in ('nowe', 'w_toku') then
    if txt is null then raise exception 'Wpisz pytanie'; end if;
    update public.zlecenia set status = 'pytanie' where id = p_id;
    insert into public.zlecenia_wpisy (zlecenie_id, author_id, kind, body) values (p_id, me, 'pytanie', txt);
    perform public.zlecenie_notify(p_id, 'pytanie');
  elsif p_akcja = 'zglos' and z.assignee_id = me and z.status in ('nowe', 'w_toku', 'pytanie') then
    update public.zlecenia set status = 'zgloszone', reported_at = now() where id = p_id;
    insert into public.zlecenia_wpisy (zlecenie_id, author_id, kind, body) values (p_id, me, 'zgloszenie', txt);
    perform public.zlecenie_notify(p_id, 'zgloszone');
  elsif p_akcja = 'akceptuj' and adm and z.status = 'zgloszone' then
    update public.zlecenia set status = 'zaakceptowane', accepted_at = now() where id = p_id;
    insert into public.zlecenia_wpisy (zlecenie_id, author_id, kind, body) values (p_id, me, 'akceptacja', txt);
    perform public.zlecenie_notify(p_id, 'zaakceptowane');
  elsif p_akcja = 'popraw' and adm and z.status = 'zgloszone' then
    if txt is null then raise exception 'Napisz, co poprawić'; end if;
    update public.zlecenia set status = 'w_toku', reported_at = null where id = p_id;
    insert into public.zlecenia_wpisy (zlecenie_id, author_id, kind, body) values (p_id, me, 'poprawka', txt);
    perform public.zlecenie_notify(p_id, 'poprawka');
  elsif p_akcja = 'odpowiedz' and adm and z.status = 'pytanie' then
    if txt is null then raise exception 'Wpisz odpowiedź'; end if;
    update public.zlecenia set status = 'w_toku' where id = p_id;
    insert into public.zlecenia_wpisy (zlecenie_id, author_id, kind, body) values (p_id, me, 'komentarz', txt);
    perform public.zlecenie_notify(p_id, 'odpowiedz');
  elsif p_akcja = 'anuluj' and adm and z.status not in ('zaakceptowane', 'anulowane') then
    update public.zlecenia set status = 'anulowane' where id = p_id;
    insert into public.zlecenia_wpisy (zlecenie_id, author_id, kind, body) values (p_id, me, 'status', coalesce(txt, 'Anulowano'));
  elsif p_akcja = 'wznow' and adm and z.status in ('zaakceptowane', 'anulowane') then
    update public.zlecenia set status = 'w_toku', accepted_at = null where id = p_id;
    insert into public.zlecenia_wpisy (zlecenie_id, author_id, kind, body) values (p_id, me, 'status', 'Wznowiono');
  else
    raise exception 'Tej czynności nie można teraz wykonać';
  end if;
  return (select status from public.zlecenia where id = p_id);
end $$;
revoke all on function public.zlecenie_akcja(uuid, text, text) from public, anon;
grant execute on function public.zlecenie_akcja(uuid, text, text) to authenticated;

-- odhaczanie kroków (pracownik albo administrator)
create or replace function public.zlecenie_krok(p_id uuid, p_idx int, p_done boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
declare z public.zlecenia%rowtype; me uuid := public.current_member_id();
begin
  select * into z from public.zlecenia where id = p_id for update;
  if not found or me is null or (not public.is_admin() and z.assignee_id <> me) then raise exception 'Brak dostępu do zlecenia'; end if;
  if p_idx < 0 or p_idx >= jsonb_array_length(z.steps) then raise exception 'Nie ma takiego kroku'; end if;
  update public.zlecenia set steps = jsonb_set(steps, array[p_idx::text, 'done'], to_jsonb(p_done)),
    status = case when status = 'nowe' and z.assignee_id = me then 'w_toku' else status end
   where id = p_id returning steps into z.steps;
  return z.steps;
end $$;
revoke all on function public.zlecenie_krok(uuid, int, boolean) from public, anon;
grant execute on function public.zlecenie_krok(uuid, int, boolean) to authenticated;
